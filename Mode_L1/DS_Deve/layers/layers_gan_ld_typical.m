function layers = layers_gan_ld_typical()
%LAYERS_GAN_LD_TYPICAL  450 nm GaN 基蓝光 LD 的典型垂直层序（量级起点）
%
%   layers = layers_gan_ld_typical()
%
%   层序由下至上（y 从小到大）：
%     #  tag         材料              厚度 [μm]    n @450 nm   备注
%     1  substrate   Al2O3 (蓝宝石)      Inf        1.770      半无限
%     2  n-clad      n-Al0.06GaN         1.200      2.404
%     3  n-wave      n-In0.04GaN         0.120      2.455      波导层
%     4  QW          In0.15GaN           0.009      2.550      有源区(1 层等效)
%     5  p-wave      p-In0.04GaN         0.080      2.455      波导层
%     6  p-clad      p-Al0.10GaN         0.400      2.374
%     7  cover       空气                Inf        1.000      半无限
%
%   ── ⚠ 这份层序的定位 ────────────────────────────────────────
%   它只是【典型量级起点】，用来把求解器跑通、把 Γ 与模场剖面画出来。
%   真实外延结构【企业有外延能力，应优先索取】，拿到后请整体替换本文件，
%   不要在原文件上改数字——保留本文件作为"文献典型值"的对照组。
%
%   ── 折射率取值的来源与不确定度 ──────────────────────────────
%   取值锚在文献清单 §4 核实表给的折射率对比：
%       GaN 与 Al0.06GaN 的折射率差 ≈ 0.026
%       In0.04GaN 波导与 Al0.14GaN 包层的差 ≈ 0.06
%   由 GaN ≈ 2.43 @450 nm 按此梯度外推得到表中各值。这些是【量级可靠、
%   末位不可靠】的数，不适用于任何定量对标；阶段1 的验证刻意设计为不依赖
%   它们的绝对值（见 A3 的 V 数验证），正是为了回避这一点。
%
%   ── 几处刻意的简化（阶段1 允许，后续阶段必须处理）───────────
%   (1) cover 取空气 (n = 1.0)：真实器件该位置是 p-GaN 接触层 + Pd 电极。
%       Pd 在 450 nm 的吸收系数高达约 8.9e5 cm^-1，是阶段2 的独立损耗通道。
%       此处用空气代替，等价于假设"金属把光完美截止且不吸收"，会低估损耗。
%   (2) QW 用单层等效 (9 nm, In0.15GaN) 代替多层 InGaN/GaN MQW：
%       阶段1 只需一个高折射率薄层来构成芯，多层化不改变本征方程的数学结构。
%       阶段2 起若要算 Γ 与阱垒的精细重叠，必须展开成真实的阱/垒层序。
%   (3) 全部折射率取实（n'' = 0）：阶段2 给 Mg 掺杂层与衬底赋虚部即可生效。
%   ────────────────────────────────────────────────────────────

layers = struct( ...
    'd', ...
        { Inf,      1.200,      0.120,      0.009,      0.080,      0.400,      Inf      }, ...
    'n', ...
        { 1.770,    2.404,      2.455,      2.550,      2.455,      2.374,      1.000    }, ...
    'tag', ...
        {'substrate','n-clad',  'n-wave',   'QW',       'p-wave',   'p-clad',   'cover'  }, ...
    'is_active', ...
        { false,    false,      false,      true,       false,      false,      false    });
end
