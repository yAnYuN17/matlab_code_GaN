function layers = layers_gan_ld_ebl()
%LAYERS_GAN_LD_EBL  450 nm GaN 基蓝光 LD 的 7 层垂直结构（显式含 EBL）
%
%   layers = layers_gan_ld_ebl()
%
%   层序由下至上（y 从小到大）：
%
%     #  tag         材料             厚度 [μm]    n @450 nm   角色
%     ─────────────────────────────────────────────────────────────────
%     1  substrate   Al2O3 (蓝宝石)     Inf         1.770     衬底（半无限）
%     2  n-clad      n-Al0.06GaN        1.200       2.404     n 侧包层
%     3  n-wave      n-In0.04GaN        0.120       2.455     n 侧波导层
%     4  QW          In0.15GaN          0.009       2.550     有源区（单层等效）
%     5  p-wave      u-In0.04GaN        0.080       2.455     p 侧无掺杂波导层
%     6  EBL         p-Al0.20GaN        0.020       2.343     电子阻挡层
%     7  p-clad      p-Al0.10GaN        Inf         2.374     p 侧包层（半无限）
%
%   ── 与 layers_gan_ld_typical.m 的差别（两个）──────────────────
%   (1) 顶层由【空气】换成【p-Al0.10GaN 半无限】。
%       物理含义：不再假设"金属把光完美截止"，而是让 p 包层作为真正的
%       光学包层。这样 p 侧的光场分布由 p 包层折射率决定，而不是由一个
%       折射率 1.0 的人工界面决定。代价是忽略了 p 包层之上的 p-GaN 接触层
%       与 Pd 电极——那是一条独立的吸收通道，属阶段 2。
%   (2) 在 QW 与 p 包层之间显式插入【EBL】层。
%       EBL 的折射率（2.343）低于两侧的 p 波导（2.455）与 p 包层（2.374），
%       形成一个折射率凹陷。它同时起两个作用：阻挡电子（电学），以及
%       把光场往 n 侧推、减少 p 侧吸收（光学）。这个凹陷是本层序里
%       唯一"非单调"的折射率台阶，也是 TE1 等高阶模行为变化的原因。
%
%   ── 折射率取值 ─────────────────────────────────────────────
%   锚点：GaN @450 nm ≈ 2.43；GaN 与 Al0.06GaN 的折射率差 ≈ 0.026
%         （文献实测对比，见交接报告文献清单 §4）。
%   由此得 AlGaN 的组分斜率 ≈ 0.026/0.06 ≈ 0.433（每单位 Al 组分）。
%       Al0.06GaN : 2.43 − 0.06×0.433 = 2.404
%       Al0.10GaN : 2.43 − 0.10×0.433 = 2.387  → 沿用族内一致的 2.374
%       Al0.20GaN : 2.43 − 0.20×0.433 = 2.343   ← 本函数的 EBL
%       In0.04GaN : 2.455（由 In 侧外推，沿用族内值）
%       In0.15GaN : 2.550（由 In 侧外推，沿用族内值）
%
%   ⚠ 全部折射率都是【量级可靠、末位不可靠】的典型值，不适用于任何
%     定量对标。真实外延结构应尽早向企业索取并整体替换本文件。
%
%   ⚠ 几处刻意的简化（阶段 1 允许，后续阶段必须处理）
%     (1) QW 用单层等效（9 nm, In0.15GaN）代替多层 InGaN/GaN MQW。
%         阶段 2 起若要算 Γ 与阱垒的精细重叠，必须展开成真实阱/垒层序。
%     (2) EBL 厚度取 20 nm、无渐变。真实 EBL 常见 10–25 nm，
%         且可能有 Al 组分渐变，会改变凹陷深度与光场推离的效果。
%     (3) 全部折射率取实（n'' = 0）。阶段 2 给 Mg 掺杂层与衬底赋虚部即可生效。
%
%   ⚠ 首尾两层厚度必须是 Inf（半无限）——build_layers.m 会直接报错而不是
%     静默容忍。把最外层截断成有限厚度会人为引入一个界面，
%     解出物理上不存在的"假离散模"。

layers = struct( ...
    'd', ...
        { Inf,      1.200,      0.120,      0.009,      0.080,      0.020,      Inf      }, ...
    'n', ...
        { 1.770,    2.404,      2.455,      2.550,      2.455,      2.343,      2.374    }, ...
    'tag', ...
        {'substrate','n-clad',  'n-wave',   'QW',       'p-wave',   'EBL',      'p-clad' }, ...
    'is_active', ...
        { false,    false,      false,      true,       false,      false,      false    });
end
