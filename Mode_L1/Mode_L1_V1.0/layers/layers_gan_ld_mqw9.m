function layers = layers_gan_ld_mqw9()
%LAYERS_GAN_LD_MQW9  450 nm GaN 基蓝光 LD 的 9 层垂直结构（MQW 展开版）
%
%   layers = layers_gan_ld_mqw9()
%
%   本文件是 layers_gan_ld_ebl.m 的【加层示例】：把那里面的单层等效 QW
%   （9 nm In0.15GaN）展开成 阱-垒-阱 三层，总层数 7 → 9。
%   除此之外每一个数字都与 layers_gan_ld_ebl.m 完全相同。
%
%   层序由下至上（y 从小到大）：
%
%     #  tag         材料             厚度 [μm]    n @450 nm   角色
%     ─────────────────────────────────────────────────────────────────
%     1  substrate   Al2O3 (蓝宝石)     Inf         1.770     衬底（半无限）
%     2  n-clad      n-Al0.06GaN        1.200       2.404     n 侧包层
%     3  n-wave      n-In0.04GaN        0.120       2.455     n 侧波导层
%     4  QW1         In0.15GaN          0.003       2.550     阱 1   ← 有源区
%     5  barrier     GaN                0.006       2.430     垒      ← 非有源区
%     6  QW2         In0.15GaN          0.003       2.550     阱 2   ← 有源区
%     7  p-wave      u-In0.04GaN        0.080       2.455     p 侧无掺杂波导层
%     8  EBL         p-Al0.20GaN        0.020       2.343     电子阻挡层
%     9  p-clad      p-Al0.10GaN        Inf         2.374     p 侧包层（半无限）
%
%   ── 加层时【唯一】要遵守的规则 ──────────────────────────────
%   下面 struct(...) 里有四个字段数组：d / n / tag / is_active。
%   它们必须【等长】，且第 i 个元素描述的是同一层。加层就是在四个数组的
%   同一位置各插一个元素。插错位置（比如只改了 d 没改 n）不会报错，
%   只会安静地解出一个物理上不存在的结构——这是本项目最需要防的一类错误。
%
%   ── 不需要改任何 src/ 里的代码 ──────────────────────────────
%   求解器本身对层数没有限制（路径 2 'tmm' 与路径 3 'fdm' 都是任意层数）。
%   ⚠ 唯一例外：路径 1 'analytic3' 只对【严格三层】有效，本结构必须用
%     'tmm' 或 'fdm'——solve_slab 默认就是 'tmm'，不用额外设置。
%
%   ── 垒层取 GaN (2.430) 而不是势垒的典型 InGaN 组分 ───────────
%   真实 InGaN/GaN MQW 的垒层是 GaN 或 InGaN（组分低于阱）。这里取纯 GaN，
%   是 InGaN 体系最常用的垒。折射率 2.430 由 GaN 的文献值直接给出，
%   不经过外推，所以它比阱层的 2.550 更可靠一点。
%
%   ⚠ 阱/垒厚度（3 nm / 6 nm）是【典型量级】，不是真实外延参数。
%     真实 MQW 的阱厚常在 2.5–3.5 nm、垒厚 5–15 nm，且阱数通常 2–5 个。
%     本文件只用来演示"怎么加层"，不是一份可对标的器件设计。
%
%   ⚠ Γ 的口径在这个结构下依然成立且更显重要：
%     is_active 标在 QW1 与 QW2 两层上（垒层不标），所以
%         Γ = (阱1 + 阱2 的功率) / 总功率
%     这正是 confinement_factor.m 首行定义的"全部有源层的并集，不含势垒"。
%     若把垒层也标成 is_active，Γ 会变大但含义变了——两者不可混用。

layers = struct( ...
    'd', ...
        { Inf,   1.200,   0.120,   0.003,   0.006,   0.003,   0.080,   0.020,   Inf    }, ...
    'n', ...
        { 1.770, 2.404,   2.455,   2.550,   2.430,   2.550,   2.455,   2.343,   2.374  }, ...
    'tag', ...
        {'substrate','n-clad','n-wave','QW1','barrier','QW2','p-wave','EBL','p-clad'}, ...
    'is_active', ...
        { false, false,   false,   true,    false,   true,    false,   false,   false  });
end
